const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM, VirtualConsole } = require('jsdom');
const root = path.resolve(__dirname, '..');
const tick = () => new Promise(resolve => setTimeout(resolve, 15));

test('standalone lecture works on file URL without external resources', async () => {
  const errors = [];
  const vc = new VirtualConsole(); vc.on('jsdomError', e => errors.push(e.message));
  const html = fs.readFileSync(path.join(root, 'talk/index.html'), 'utf8');
  const dom = new JSDOM(html, {url:'file:///lecture/index.html', runScripts:'dangerously', virtualConsole:vc,
    beforeParse(w) {w.matchMedia = () => ({matches:false});}
  });
  const w=dom.window, d=w.document;
  await tick();
  const slides = [...d.querySelectorAll('#deck > .slide')];
  assert.equal(slides.length, 15);
  assert.equal(d.querySelectorAll('script[src], link[rel=stylesheet], img[src]').length, 0);
  assert.equal(d.querySelectorAll('#nav button').length, 15);
  assert.equal(d.querySelectorAll('.page-no').length, 15);
  assert.equal(slides[0].classList.contains('active'), true);
  d.getElementById('next').click();
  assert.equal(slides[1].classList.contains('active'), true);
  assert.equal(slides[0].getAttribute('aria-hidden'), 'true');
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'n'}));
  assert.equal(d.getElementById('speaker-panel').hidden, false);
  assert.match(d.getElementById('note-title').textContent, /专题安排/);
  assert.ok(d.getElementById('note-body').textContent.length > 80);
  const prior=w.location.hash;
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowRight'}));
  assert.equal(w.location.hash, prior, 'notes reading must not accidentally change slide');
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape'}));
  assert.equal(d.getElementById('speaker-panel').hidden, true);
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowRight'}));
  assert.equal(slides[2].classList.contains('active'), true);
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'b'}));
  assert.equal(d.body.classList.contains('low-power'), true);
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape'}));
  assert.equal(d.body.classList.contains('overview'), true);
  assert.equal(d.querySelectorAll('.thumb').length, 15);
  d.querySelectorAll('.thumb')[9].click();
  assert.equal(d.body.classList.contains('overview'), false);
  assert.equal(slides[9].classList.contains('active'), true);
  d.getElementById('notes-toggle').click();
  assert.match(d.getElementById('note-body').textContent, /4352/);
  assert.ok(d.getElementById('note-sources').querySelector('a[href^="https://"]'));
  d.getElementById('speaker-close').click();
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'End'}));
  assert.equal(d.getElementById('next').disabled, true);
  w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Home'}));
  assert.equal(d.getElementById('previous').disabled, true);
  w.location.hash='chapter-two';await tick();
  assert.equal(slides[13].classList.contains('active'), true);
  assert.match(slides[13].textContent, /预留章节/);
  assert.deepEqual(errors, []);
  w.close();
});
